# ==============================================================================
# make_autosomes_table.R
# Convert results/bench_full/12_mouse_autosomes_summary.csv into LaTeX.
# Output: theory/tab_realdata_autosomes.tex
# ==============================================================================

IN  <- "results/bench_full/12_mouse_autosomes_summary.csv"
dir.create("theory", showWarnings = FALSE)
TEX <- "theory/tab_realdata_autosomes.tex"

if (!file.exists(IN)) {
  message("(skipped: ", IN, " not found)"); quit("no", status = 0L)
}

df <- read.csv(IN, stringsAsFactors = FALSE)

METHOD_ORDER <- c("JS_L_eBIC", "MS_L_eBIC", "JS_L_JP99", "MS_L_JP99",
                   "BayesR", "BSLMM", "SuSiE", "fastlmm")
METHOD_LATEX <- c(
  JS_L_eBIC = "\\textsc{JS-LMM}-eBIC",
  MS_L_eBIC = "\\textsc{MS-LMM}-eBIC",
  JS_L_JP99 = "\\textsc{JS-LMM}-JP99",
  MS_L_JP99 = "\\textsc{MS-LMM}-JP99",
  BayesR    = "BayesR",
  BSLMM     = "BSLMM",
  SuSiE     = "SuSiE",
  fastlmm   = "FaST-LMM"
)

df$method <- factor(df$method, levels = METHOD_ORDER)
df <- df[order(df$method), ]

rows <- character()
for (i in seq_len(nrow(df))) {
  r <- df[i, ]
  rows[i] <- sprintf("%s & $%d$ & $%d$ & %s \\\\",
                       METHOD_LATEX[as.character(r$method)],
                       r$K_hat, r$n_chr, r$chr_distribution)
}

body <- c(
  "% AUTO-GENERATED by make_autosomes_table.R",
  "\\begin{tabular}{l rr l}",
  "\\toprule",
  "Method & $\\hat K$ & \\# chr.\\ & Target chromosomes (\\# SNPs) \\\\",
  "\\midrule",
  rows,
  "\\bottomrule",
  "\\end{tabular}"
)
writeLines(body, TEX)
message("Wrote ", TEX)
